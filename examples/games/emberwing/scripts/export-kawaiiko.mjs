// Author in Studio; bake three colored meshes for the independent game runtime.
// Run from the repository root after building Studio's modeling/bridge package.
import { writeFile } from "node:fs/promises";
import { kawaiikoDocument } from "../../../../editor/studio/modeling/model.mjs";
import { meshGeometry } from "../../../../editor/studio/modeling/geometry.mjs";

const groups = [[], [], []];
for (const node of kawaiikoDocument().nodes) {
  const group = node.id.startsWith("wing.") ? (node.id.endsWith("left") ? 1 : 2) : 0;
  const indexed = meshGeometry(node), mesh = indexed.toNonIndexed();
  mesh.computeVertexNormals();
  const p = mesh.getAttribute("position"), n = mesh.getAttribute("normal");
  for (let i = 0; i < p.count; i++) {
    const pivot = group === 1 ? -0.59 : group === 2 ? 0.59 : 0;
    groups[group].push(
      (p.getX(i) + node.position[0] - pivot) * 0.85,
      (p.getY(i) + node.position[1] - (group ? 1.17 : 0)) * 0.85,
      (p.getZ(i) + node.position[2] + (group ? 0.15 : 0)) * 0.85,
      n.getX(i), n.getY(i), n.getZ(i), node.color, 0,
    );
  }
  indexed.dispose(); mesh.dispose();
}
const json = JSON.stringify(groups.map((g) => g.map((x) => Math.round(x * 100000) / 100000)));
await writeFile(new URL("../kawaiiko_generated.mbt", import.meta.url),
  "// Generated by scripts/export-kawaiiko.mjs from Studio's kawaiiko model.\n" +
  "// Source art: https://github.com/chibivue-land/art (see README.md).\n///|\nlet kawaiiko_source : String =\n  #|" + json.replace(/(.{1,1800},)/g, "$1\n  #|") + "\n");
console.log(`Baked kawaiiko: ${groups.map((g) => g.length / 24).join(" + ")} triangles, three shared meshes.`);
