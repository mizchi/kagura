#!/usr/bin/env node
// Writes the spatial3d problems as MoonBit test data for
// `mizchi/kagura_core/collision3d/convex` (convex_check/fixture_wbtest.mbt).
// The answers are this benchmark's certified ground truth, so the MoonBit
// GJK is checked against an independent implementation.
//
//   node benchmarks/spatial3d/export-convex-fixture.mjs && moon fmt
//
// v3 gives distances; v2 gives yes/no intersections with margins down to
// 0.2% of the object size. Tori are left out: they are not convex and have
// no decomposition into convex pieces.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { convexParts } from "./lib/geometry.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const rows = (v, f) => readFileSync(join(here, "data", v, f), "utf8").trim().split("\n").map(JSON.parse);

const num = (x) => {
  const s = String(x);
  return /[.e]/.test(s) ? s : `${s}.0`;
};
const vec = (p) => `v(${p.map(num).join(", ")})`;

function shape(s) {
  switch (s.type) {
    case "point":
      return `Point(at=${vec(s.position)})`;
    case "sphere":
      return `Sphere(center=${vec(s.center)}, radius=${num(s.radius)})`;
    case "aabb":
      return `@convex.Shape::aabb(min=${vec(s.min)}, max=${vec(s.max)})`;
    case "obb":
      // The benchmark writes quaternions as [w, x, y, z]; `wxyz` reorders.
      return `Box(center=${vec(s.center)}, half_extents=${vec(s.half_extents)}, rotation=wxyz(${s.rotation.map(num).join(", ")}))`;
    case "segment":
      return `Segment(start=${vec(s.a)}, end=${vec(s.b)})`;
    case "capsule":
      return `Capsule(start=${vec(s.a)}, end=${vec(s.b)}, radius=${num(s.radius)})`;
    case "cylinder":
      return `Cylinder(start=${vec(s.a)}, end=${vec(s.b)}, radius=${num(s.radius)})`;
    case "cone":
      return `Cone(base_center=${vec(s.base_center)}, apex=${vec(s.apex)}, radius=${num(s.radius)})`;
    case "triangle":
    case "tetrahedron":
      return `Hull(vertices=[${s.vertices.map(vec).join(", ")}])`;
    default:
      throw new Error(`unexpected ${s.type}`);
  }
}

const parts = (o) => `[${convexParts(o).map(shape).join(", ")}]`;

function cases(version, value) {
  const answers = new Map(rows(version, "answers.jsonl").map((a) => [a.id, a]));
  return rows(version, "problems.jsonl")
    .filter((p) => p.task !== "scene" && !p.objects.some((o) => o.type === "torus"))
    .map((p) => `  ("${version}/${p.id}", ${parts(p.objects[0])}, ${parts(p.objects[1])}, ${value(answers.get(p.id).answer)}),`);
}

const v3 = cases("v3", (d) => num(d));
const v2 = cases("v2", (yes) => String(yes));
const out = `// Generated by benchmarks/spatial3d/export-convex-fixture.mjs. Do not edit.

///|
/// spatial3d v3: (id, pieces of A, pieces of B, certified distance rounded to 6 decimals).
let v3_distances : Array[(String, Array[@convex.Shape], Array[@convex.Shape], Double)] = [
${v3.join("\n")}
]

///|
/// spatial3d v2: (id, pieces of A, pieces of B, whether they intersect).
let v2_intersections : Array[(String, Array[@convex.Shape], Array[@convex.Shape], Bool)] = [
${v2.join("\n")}
]
`;
const dest = join(here, "convex_check", "fixture_wbtest.mbt");
writeFileSync(dest, out);
console.log(`wrote ${v3.length} distance and ${v2.length} intersection cases to ${dest}`);
